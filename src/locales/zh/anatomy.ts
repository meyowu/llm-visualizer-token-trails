const TOKS = ['The', 'Ġcat', 'Ġsat', 'Ġon', 'Ġthe']
/** One entry per prompt token for notes that name the hovered token ($a, and $b for a second one). */
function perToken(key: string, value: string, two = false): Record<string, string> {
  const out: Record<string, string> = {}
  for (const a of TOKS) for (const b of two ? TOKS : ['']) out[key.replace(/\$a/g, a).replace(/\$b/g, b)] = value.replace(/\$a/g, a).replace(/\$b/g, b)
  return out
}

